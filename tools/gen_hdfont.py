#!/usr/bin/env python3
"""gen_hdfont.py: bakes the menu's fonts into src/hfont_data.c.

M PLUS 1p (SIL OFL 1.1, tools/fonts: the DSi's own lettering is a plain rounded-cornered sans, closer to it than a
rounded face), drawn at the RG DS Plus's own pixels (1024x768 a screen): each size the
menu uses, rasterized once here with 16 levels of coverage (4 bits a pixel), so the handheld needs no font engine.

    python3 tools/gen_hdfont.py        (needs Pillow; rerun after changing FONTS or CHARS)
"""
import os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'src', 'hfont_data.c')

ASCII = list(range(0x20, 0x7f)) + list(range(0xa0, 0x100)) + [
    0x2013, 0x2014, 0x2018, 0x2019, 0x201c, 0x201d, 0x2022, 0x2026, 0x2122, 0x2192, 0x2190]
ASCII = sorted(set(ASCII))                 # (code point order: the menu finds them by halving)
DIGITS = sorted(ord(c) for c in '0123456789: ')

# (C name, weight, pixel size, characters)
FONTS = [
    ('HF_CAPS',   'ExtraBold', 21, ASCII),   # small capitals labels ("CONTINUE", "SAVE STATES")
    ('HF_SMALL',  'Medium',    22, ASCII),   # secondary lines
    ('HF_BODY',   'Medium',    26, ASCII),   # body text
    ('HF_BODYB',  'Bold',      26, ASCII),   # chips, values
    ('HF_LABEL',  'ExtraBold', 28, ASCII),   # buttons, rows, tabs
    ('HF_BTN',    'ExtraBold', 33, ASCII),   # the main buttons
    ('HF_TITLE',  'ExtraBold', 36, ASCII),   # the selected game's name, page titles
    ('HF_HERO',   'ExtraBold', 54, ASCII),   # the top screen's title
    ('HF_HUGE',   'ExtraBold', 80, ASCII),   # the start-up's and the sleep's words
    ('HF_CLOCK',  'ExtraBold', 150, DIGITS), # the big clock
    ('HF_MD',     'Medium',    40, ASCII),   # the DSi's body text (its 12 px, x4 less a touch: the XL's panels)
    ('HF_BD',     'Bold',      40, ASCII),   # its titles, buttons, tabs
    ('HF_LG',     'ExtraBold', 60, ASCII),   # the emblem ("Nintendo DS"), big labels
    ('HF_LOGO',   'ExtraBold', 84, ASCII),   # a game's name as a logo on the top screen
    ('HF_XS',     'Bold',      32, ASCII),   # the status bar, small print
]


def quant(v):
    return (v * 15 + 127) // 255          # 0..15


def bake(weight, size, chars):
    font = ImageFont.truetype(os.path.join(HERE, 'fonts', 'MPLUS1p-%s.ttf' % weight), size)
    ascent, descent = font.getmetrics()
    glyphs, atlas = [], bytearray()
    for cp in chars:
        ch = chr(cp)
        adv = int(round(font.getlength(ch)))
        bbox = font.getbbox(ch)
        if bbox[2] <= bbox[0] or bbox[3] <= bbox[1]:
            glyphs.append((cp, len(atlas), 0, 0, 0, 0, adv))
            continue
        w, h = bbox[2] - bbox[0], bbox[3] - bbox[1]
        im = Image.new('L', (w, h), 0)
        d = ImageDraw.Draw(im)
        d.text((-bbox[0], -bbox[1]), ch, font=font, fill=255)
        px = im.load()
        off = len(atlas)
        for y in range(h):
            for x in range(0, w, 2):
                a = quant(px[x, y]); b = quant(px[x + 1, y]) if x + 1 < w else 0
                atlas.append(a | (b << 4))
        glyphs.append((cp, off, w, h, bbox[0], bbox[1], adv))
    return ascent, descent, glyphs, atlas


def main():
    out = ['// hfont_data.c: generated by tools/gen_hdfont.py from M PLUS Rounded 1c (SIL Open Font License 1.1).',
           '// Do not edit: rerun the script.', '#include "hfont.h"', '']
    tables = []
    for name, weight, size, chars in FONTS:
        asc, desc, glyphs, atlas = bake(weight, size, chars)
        low = name.lower()
        out.append('static const uint8_t %s_bits[%d] = {' % (low, max(1, len(atlas))))
        for i in range(0, len(atlas), 32):
            out.append('    ' + ','.join(str(b) for b in atlas[i:i + 32]) + ',')
        if not atlas:
            out.append('    0')
        out.append('};')
        out.append('static const HGlyph %s_glyphs[%d] = {' % (low, len(glyphs)))
        for g in glyphs:
            out.append('    { 0x%04x, %d, %d, %d, %d, %d, %d },' % g)
        out.append('};')
        tables.append('    { %d, %d, %d, %s_glyphs, %s_bits },  /* %s %s %dpx */' % (asc, desc, len(glyphs), low, low, name, weight, size))
    out.append('const HFontData hfont_data[HF_COUNT] = {')
    out += tables
    out.append('};')
    open(OUT, 'w').write('\n'.join(out) + '\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
