#!/usr/bin/env python3
"""gen_font.py: bakes the menu's fonts into src/font_data.c.

The DSi draws its text with a hinted sans at 1:1 pixels and 2-bit (4-level) antialiasing. M PLUS 1p (SIL OFL,
tools/fonts) at 13 px lands almost exactly on the DSi's system font metrics, so it is rasterized here once,
quantized to 4 levels, and packed 2 bits per pixel. The handheld then needs no font engine at all.

    python3 tools/gen_font.py        (needs Pillow; rerun after changing FONTS or CHARS)
"""
import os
from PIL import Image, ImageDraw, ImageFont

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, '..', 'src', 'font_data.c')

# (C name, file, pixel size, extra tracking in px)
FONTS = [
    ('FONT_SM', 'MPLUS1p-Medium.ttf', 10, 0),     # small labels
    ('FONT_MD', 'MPLUS1p-Medium.ttf', 12, 0),     # body text (a touch under the DSi's 13: the XL's big panels)
    ('FONT_BD', 'MPLUS1p-Bold.ttf', 12, 0),       # titles, buttons
    ('FONT_LG', 'MPLUS1p-ExtraBold.ttf', 16, 0),  # big labels, fallback logos
    ('FONT_XL', 'MPLUS1p-ExtraBold.ttf', 26, 0),  # the bottom screen's watermark ("Nintendo DSi Menu")
    ('FONT_HS', 'MPLUS1p-Bold.ttf', 15, -1),      # the health and safety headline (condensed)
    ('FONT_XS', 'MPLUS1p-Medium.ttf', 9, 0),      # the status bar's date and time
]

CHARS = list(range(0x20, 0x7f)) + list(range(0xa0, 0x100)) + [
    0x2013, 0x2014, 0x2018, 0x2019, 0x201c, 0x201d, 0x2022, 0x2026, 0x2122, 0x2605, 0x2606, 0x2665, 0x266a,
    0x2190, 0x2191, 0x2192, 0x2193]


def quant(v):
    return (v * 3 + 127) // 255          # 0..3


def bake(name, path, size, track):
    font = ImageFont.truetype(os.path.join(HERE, 'fonts', path), size)
    ascent, descent = font.getmetrics()
    glyphs, atlas = [], []                # atlas: one 2bpp row-major bitmap per glyph, concatenated
    for cp in CHARS:
        ch = chr(cp)
        adv = int(round(font.getlength(ch))) + track
        bbox = font.getbbox(ch)           # relative to the drawing origin (top of the ascent)
        if bbox[2] <= bbox[0] or bbox[3] <= bbox[1]:
            glyphs.append((cp, len(atlas), 0, 0, 0, 0, adv))
            continue
        w, h = bbox[2] - bbox[0], bbox[3] - bbox[1]
        im = Image.new('L', (w, h), 0)
        d = ImageDraw.Draw(im)
        d.fontmode = 'L'
        d.text((-bbox[0], -bbox[1]), ch, font=font, fill=255)
        px = im.load()
        bits = [quant(px[x, y]) for y in range(h) for x in range(w)]
        if not any(bits):
            glyphs.append((cp, len(atlas), 0, 0, 0, 0, adv))
            continue
        off = len(atlas)
        for i in range(0, len(bits), 4):
            b = 0
            for k, v in enumerate(bits[i:i + 4]):
                b |= v << (k * 2)
            atlas.append(b)
        glyphs.append((cp, off, w, h, bbox[0], bbox[1], adv))
    return ascent, descent, glyphs, atlas


def main():
    out = ['// font_data.c: generated by tools/gen_font.py from M PLUS 1p (SIL Open Font License 1.1, tools/fonts/OFL.txt).',
           '// Do not edit: rerun the script.', '#include "font.h"', '']
    tables = []
    for name, path, size, track in FONTS:
        asc, desc, glyphs, atlas = bake(name, path, size, track)
        low = name.lower()
        out.append('static const uint8_t %s_bits[%d] = {' % (low, max(1, len(atlas))))
        for i in range(0, len(atlas), 24):
            out.append('    ' + ','.join(str(b) for b in atlas[i:i + 24]) + ',')
        if not atlas:
            out.append('    0')
        out.append('};')
        out.append('static const Glyph %s_glyphs[%d] = {' % (low, len(glyphs)))
        for g in glyphs:
            out.append('    { 0x%04x, %d, %d, %d, %d, %d, %d },' % g)
        out.append('};')
        tables.append('    { %d, %d, %d, %s_glyphs, %s_bits },  /* %s %s %dpx */' % (asc, desc, len(glyphs), low, low, name, path, size))
    out.append('const FontData font_data[FONT_COUNT] = {')
    out += tables
    out.append('};')
    open(OUT, 'w').write('\n'.join(out) + '\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
